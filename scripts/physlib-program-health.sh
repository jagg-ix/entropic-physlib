#!/usr/bin/env bash
#
# Regenerate the program-health synthesis dashboard.
#
# Builds Physlib.Meta.ProgramHealth (which imports the whole library and invokes
# #physlib_program_health), captures the logged dashboard, and writes it to
# analysis/program-health.md. Run from the repository root:
#
#   ./scripts/physlib-program-health.sh
#
set -eo pipefail

module="Physlib.Meta.ProgramHealth"
source="Physlib/Meta/ProgramHealth.lean"
out="analysis/program-health.md"

mkdir -p "$(dirname "$out")"

echo "Building $module (whole-library synthesis; takes a few minutes)"
touch "$source"
log="$(lake build "$module" 2>&1)"

dash="$(printf '%s\n' "$log" | awk '
  /# physlib program-health synthesis/ { cap = 1 }
  cap && /Build completed/            { cap = 0 }
  cap                                 { print }
' | sed -E 's/^info: [^ ]+:[0-9]+:[0-9]+: //')"

if [ -z "$dash" ]; then
  echo "error: no dashboard captured — build may have failed:" >&2
  printf '%s\n' "$log" | grep -E "error:" >&2 || true
  exit 1
fi

{
  echo "<!-- generated by scripts/physlib-program-health.sh on $(date -u '+%Y-%m-%d %H:%M UTC') -->"
  echo
  printf '%s\n' "$dash"
} > "$out"

echo
echo "Wrote $out"
printf '%s\n' "$dash"
