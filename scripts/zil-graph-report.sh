#!/usr/bin/env bash
#
# Regenerate the repo-wide ZIL knowledge-graph gap audit.
#
# Builds `Physlib.Meta.ZilGraphAuditFull` (which imports the whole `Physlib`
# library and invokes `#zil_graph_report`), captures the audit it logs, and
# writes it to analysis/zil-graph-report.md. Run from the repository root:
#
#   ./scripts/zil-graph-report.sh
#
set -eo pipefail

module="Physlib.Meta.ZilGraphAuditFull"
source="Physlib/Meta/ZilGraphAuditFull.lean"
out="analysis/zil-graph-report.md"

mkdir -p "$(dirname "$out")"

echo "Building $module (repo-wide audit via the indexed evaluator; expect a couple of minutes)"
# touch so the audit `logInfo` is re-emitted even when the module is cached
touch "$source"
# Do not let `set -e` abort here: a failed or killed build should reach the
# "no audit output captured" branch below, which prints the actual errors.
if log="$(lake build "$module" 2>&1)"; then
  build_status=0
else
  build_status=$?
  echo "warning: lake build exited $build_status; attempting to salvage audit output" >&2
fi

audit="$(printf '%s\n' "$log" | awk '
  /ZilGraphAuditFull\.lean.*physlib ZIL knowledge-graph audit/ { cap=1; next }
  cap && /^[[:space:]]/ { print; next }
  cap { cap=0 }
')"

if [ -z "$audit" ]; then
  echo "error: no audit output captured (lake build exit $build_status):" >&2
  printf '%s\n' "$log" | grep -E "error:" >&2 || true
  exit 1
fi

{
  echo "# physlib ZIL knowledge-graph gap audit"
  echo
  echo "Generated by \`scripts/zil-graph-report.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
  echo "Rules: \`Physlib.Meta.ZilGraph.improvementRules\` (stratified-negation gap detectors)."
  echo
  echo '```'
  printf '%s\n' "$audit"
  echo '```'
} > "$out"

echo
echo "Wrote $out:"
printf '%s\n' "$audit"
